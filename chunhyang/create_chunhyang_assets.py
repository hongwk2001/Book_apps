"""
Draw the 춘향전 launcher icon and Play Store graphics from one set of shapes.

The motif is the swing at Gwanghallu (the scene where Master Yi first sees
Chunhyang): a willow branch, two ropes, and a red seat. The same geometry is
written as the adaptive-icon vector and rendered to PNG.

Writes:
  src/main/res/mipmap-anydpi-v26/ic_launcher_foreground.xml
  ../play_store_assets/chunhyang/play_store_icon.png   (512x512)
  ../play_store_assets/chunhyang/feature_graphic.png   (1024x500)
"""
import os

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
STORE = os.path.join(HERE, "..", "play_store_assets", "chunhyang")
OCHRE = "#7C5A14"
CREAM = "#F4E9D2"
RED = "#D9573C"
LEAF = "#C9D98A"

# Geometry in the 108x108 adaptive-icon viewport (safe zone is the central 66).
BRANCH = [(14, 44), (26, 34), (40, 28), (56, 25), (72, 25), (86, 28), (96, 33)]  # polyline
LEAVES = [(24, 36, 21, 52), (33, 31, 31, 49), (49, 26, 48, 40), (79, 26, 81, 44), (89, 29, 92, 47)]
ROPES = [((44, 27), (56, 72)), ((64, 25), (76, 70))]
SEAT = (51, 70, 81, 76)


def vector_xml():
    branch = "M" + " L".join(f"{x},{y}" for x, y in BRANCH)
    leaves = "".join(f'\n    <path android:strokeColor="{LEAF}" android:strokeWidth="2.2" android:strokeLineCap="round" '
                     f'android:pathData="M{a},{b} L{c},{d}" />' for a, b, c, d in LEAVES)
    ropes = "".join(f'\n    <path android:strokeColor="{CREAM}" android:strokeWidth="1.8" android:strokeLineCap="round" '
                    f'android:pathData="M{p[0]},{p[1]} L{q[0]},{q[1]}" />' for p, q in ROPES)
    x0, y0, x1, y1 = SEAT
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by create_chunhyang_assets.py: the swing at Gwanghallu. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:strokeColor="{CREAM}" android:strokeWidth="3.2" android:strokeLineCap="round"
        android:strokeLineJoin="round" android:pathData="{branch}" />{leaves}{ropes}
    <path android:fillColor="{RED}"
        android:pathData="M{x0 + 2},{y0} L{x1 - 2},{y0} Q{x1},{y0} {x1},{y0 + 2} L{x1},{y1 - 2} Q{x1},{y1} {x1 - 2},{y1} L{x0 + 2},{y1} Q{x0},{y1} {x0},{y1 - 2} L{x0},{y0 + 2} Q{x0},{y0} {x0 + 2},{y0} Z" />
</vector>
"""


def draw_swing(draw, s, ox=0, oy=0):
    """Draw the motif scaled by s, offset by (ox, oy), in PIL coordinates."""
    pt = lambda x, y: (ox + x * s, oy + y * s)
    draw.line([pt(*p) for p in BRANCH], fill=CREAM, width=round(3.2 * s), joint="curve")
    for a, b, c, d in LEAVES:
        draw.line([pt(a, b), pt(c, d)], fill=LEAF, width=round(2.2 * s))
    for p, q in ROPES:
        draw.line([pt(*p), pt(*q)], fill=CREAM, width=round(1.8 * s))
    x0, y0, x1, y1 = SEAT
    draw.rounded_rectangle([pt(x0, y0), pt(x1, y1)], radius=2 * s, fill=RED)


def font(path, size):
    try:
        return ImageFont.truetype(path, size)
    except OSError:
        return ImageFont.load_default()


def main():
    with open(os.path.join(HERE, "src", "main", "res", "mipmap-anydpi-v26", "ic_launcher_foreground.xml"),
              "w", encoding="utf-8", newline="\n") as fh:
        fh.write(vector_xml())
    os.makedirs(STORE, exist_ok=True)

    icon = Image.new("RGB", (512, 512), OCHRE)
    draw_swing(ImageDraw.Draw(icon), 512 / 108)
    icon.save(os.path.join(STORE, "play_store_icon.png"))

    fg = Image.new("RGB", (1024, 500), OCHRE)
    d = ImageDraw.Draw(fg)
    draw_swing(d, 4.6, ox=520, oy=0)
    serif = r"C:\Windows\Fonts\NotoSerifKR-VF.ttf"
    d.text((70, 120), "춘향전", font=font(serif, 120), fill=CREAM)
    d.text((74, 290), "The Tale of Chunhyang", font=font(serif, 44), fill=CREAM)
    d.text((76, 360), "Korean · English bilingual reader", font=font(serif, 28), fill=LEAF)
    fg.save(os.path.join(STORE, "feature_graphic.png"))
    print("wrote icon vector, play_store_icon.png, feature_graphic.png")


if __name__ == "__main__":
    main()
